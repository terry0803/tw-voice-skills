COMPILED = [(cat, label, re.compile(rx)) for cat, label, rx in L]


def hits(text):
    """回傳這段文字命中的項目索引。"""
    return [i for i, (_, _, rx) in enumerate(COMPILED) if rx.search(text)]


def example(text, i, width=50):
    """命中項目所在的句子（給報告用）。"""
    rx = COMPILED[i][2]
    out = []
    for s in re.split(r"(?<=[。！？])|\n", text):
        if rx.search(s) and s.strip():
            out.append(s.strip()[:width * 2])
    return out

